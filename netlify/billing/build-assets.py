"""Builds netlify/billing/assets.mts: the fonts and images the invoice PDF embeds, as base64.

Run from the repo root after `npm install` (needs `pip install fonttools brotli pillow`):
    python3 netlify/billing/build-assets.py

Fonts are static cuts of Archivo (SIL Open Font License), the family the payment page uses:
regular, semibold, and the wide bold used for headings.
"""
import base64, io, pathlib
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer
from fontTools.merge import Merger
from PIL import Image, ImageDraw

ROOT = pathlib.Path(__file__).resolve().parents[2]
FILES = ROOT / 'node_modules/@fontsource-variable/archivo/files'
OUT = ROOT / 'netlify/billing/assets.mts'
TMP = pathlib.Path('/tmp/billing-assets')
TMP.mkdir(exist_ok=True)

CUTS = {'regular': (400, 100), 'semibold': (600, 100), 'wide': (700, 113)}


def cut(name, wght, wdth):
    parts = []
    for subset in ('latin', 'latin-ext'):
        font = TTFont(FILES / f'archivo-{subset}-wdth-normal.woff2')
        font.flavor = None
        inst = instancer.instantiateVariableFont(font, {'wght': wght, 'wdth': wdth})
        path = TMP / f'{name}-{subset}.ttf'
        inst.save(path)
        parts.append(str(path))
    merged = Merger().merge(parts)
    buf = io.BytesIO()
    merged.save(buf)
    return buf.getvalue()


def jpeg(im, quality):
    buf = io.BytesIO()
    im.convert('RGB').save(buf, 'JPEG', quality=quality, optimize=True, progressive=False)
    return buf.getvalue()


def png(im):
    buf = io.BytesIO()
    im.save(buf, 'PNG', optimize=True)
    return buf.getvalue()


assets = {name: cut(name, *axes) for name, axes in CUTS.items()}

# The white logo mark (drawn on a black circle in the PDF).
assets['mark'] = png(Image.open(ROOT / 'public/brand/mark-160.png').convert('RGBA'))

# A wide strip of the payment page's chrome banner.
banner = Image.open(ROOT / 'public/pay-assets/banner.webp').convert('RGB')
w, h = banner.size
strip_h = round(w * 96 / 499)
top = round(h * 0.34)
assets['banner'] = jpeg(banner.crop((0, top, w, top + strip_h)).resize((1100, round(1100 * 96 / 499)), Image.LANCZOS), 82)

# Avatar for emails: the mark on a black circle (public/pay-assets/avatar.png).
size = 192
avatar = Image.new('RGBA', (size * 2, size * 2), (0, 0, 0, 0))
ImageDraw.Draw(avatar).ellipse((0, 0, size * 2 - 1, size * 2 - 1), fill=(10, 10, 10, 255))
mark = Image.open(ROOT / 'public/brand/mark-160.png').convert('RGBA').resize((size, size), Image.LANCZOS)
avatar.alpha_composite(mark, (size // 2, size // 2))
avatar.resize((size, size), Image.LANCZOS).save(ROOT / 'public/pay-assets/avatar.png', optimize=True)

lines = ['// Generated by netlify/billing/build-assets.py. Do not edit by hand.', '// Archivo is licensed under the SIL Open Font License 1.1.', '']
for name, data in assets.items():
    lines.append(f"export const {name} = '{base64.b64encode(data).decode()}';")
OUT.write_text('\n'.join(lines) + '\n')
for name, data in assets.items():
    print(f'{name}: {len(data) // 1024} KB')
